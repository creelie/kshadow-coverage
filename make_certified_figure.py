"""Rebuild the vector certificate figure and its table from the audit JSON."""
from pathlib import Path
import json
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.patches import Circle, Polygon

ROOT=Path(__file__).resolve().parent
d=json.loads((ROOT/'results/certified_mesh.json').read_text())
out=ROOT/'paper/ecog'
rows=[]
for n,k,r in [(64,1,9),(80,1,8),(112,2,10),(128,2,9),(160,2,8)]:
    rec=next(v for v in d['records'] if v['contacts']==n and v['k']==k and v['radius_mm']==r)
    assert rec['all_faces_pass']
    rows.append(f'{n} & {r} & {k} & {k-1}'+r' \\')
(out/'certified_rows.tex').write_text('% Generated by make_certified_figure.py\n'+
    '\\begin{tabular}{rrrr}\n\\toprule\n'+
    'Contacts & Radius (mm) & Multiplicity $k$ & Failures tolerated'+r' \\'+'\n\\midrule\n'+
    '\n'.join(rows)+'\n\\bottomrule\n\\end{tabular}\n')
plt.rcParams.update({'font.family':'DejaVu Sans','font.size':8.5,'axes.titlesize':8.5,'axes.spines.top':False,'axes.spines.right':False,'pdf.fonttype':42})
fig,axes=plt.subplots(1,3,figsize=(6.6,2.65),layout='constrained')
v=np.array([[0,0],[1,0],[.5,np.sqrt(3)/2]])
ax=axes[0]
ax.add_patch(Polygon(v,closed=True,facecolor='#f5f7fa',edgecolor='#253449',lw=1.3))
for p in v:
    ax.add_patch(Circle(p,.45,facecolor='#0072B2',edgecolor='#0072B2',alpha=.13))
    ax.plot(*p,'o',color='#0072B2',ms=5)
center=v.mean(axis=0)
ax.plot(*center,'x',color='#D55E00',ms=8,mew=2)
ax.annotate('uncovered centre',center,xytext=(.5,.63),ha='center',arrowprops={'arrowstyle':'-','color':'#D55E00'},color='#9b3f00')
ax.text(.5,-.13,r'$D=1,\quad r=0.45<1/\sqrt{3}$',ha='center')
ax.set(xlim=(-.12,1.12),ylim=(-.22,1),aspect='equal',title='a  Vertex samples can\nmiss the centre')
ax.axis('off')
for ax,k,label in [(axes[1],1,'b  Single coverage'),(axes[2],2,'c  Double coverage')]:
    for radius,color,marker in [(8,'#0072B2','o'),(9,'#009E73','s'),(10,'#D55E00','^')]:
        recs=[v for v in d['records'] if v['k']==k and v['radius_mm']==radius]
        ax.plot([v['contacts'] for v in recs],[v['passing_faces']/v['total_faces'] for v in recs],marker=marker,color=color,lw=1.5,ms=4,label=f'{radius} mm')
    ax.set(title=label,xlabel='Contacts in stored sequence',ylabel='Fraction of faces certified',ylim=(0,1.035),xticks=[64,96,128,160])
    ax.axhline(1,color='#566477',lw=.7,ls=':'); ax.grid(axis='y',alpha=.16)
    ax.legend(frameon=False,loc='lower right')
fig.savefig(out/'figures/certified_mesh.pdf',bbox_inches='tight')
fig.savefig(out/'figures/certified_mesh.png',dpi=220,bbox_inches='tight')
plt.close(fig)
